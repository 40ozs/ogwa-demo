"""The sanitized reviewer audit sample, generated from the application itself.

``python -m app.demo.null_meridian.audit_sample --write docs/demo/samples/ogwa-audit-sample.json``
seeds a fresh, in-memory Null Meridian store (the same seed as every demo reset), serves the real
API over it in-process (no socket), and records what the API answers for the two walkthrough
scenarios. ``--check`` regenerates it and fails if the committed file differs by one byte, which
is how ``tests/test_ogwa_demo_integration.py`` proves the sample is the application's own
serialization, not a hand-written transcript.

Every object in the sample is a verbatim JSON subtree of one API response, named by
``source``: nothing is renamed, reworded, or filled in. Determinism comes from the seed, a
synthetic clock that starts one hour after the snapshot and advances one second per reading
(as the seed's own clock does), and ``deterministic_ids`` for the ids the requests create.
Sessions are signed in through the synthetic identity adapter and their cookies and CSRF tokens
are never written. Everything is synthetic: the store refuses anything but SYNTHETIC evidence,
the drill touches only a discarded in-memory provider fixture, and nothing external is
contacted. The in-memory store is closed and discarded when the sample is built.
"""

import argparse
import io
import json
import sys
from pathlib import Path
from typing import Any

from app.api.local import build_local_api
from app.api.sessions import CSRF_HEADER, SESSION_COOKIE
from app.core.database_url import parse_database_url
from app.demo.null_meridian.profile import AS_OF, DATASET_KEY, SEED
from app.demo.null_meridian.world import create_null_meridian_store
from app.demo.synthetic_world import HOUR, SeedClock
from app.domain.ids import deterministic_ids

FORMAT = "ogwa-audit-sample/v1"
DEFAULT_PATH = Path(__file__).resolve().parents[3] / "docs" / "demo" / "samples" / "ogwa-audit-sample.json"
V = "/api/v1"
EXECUTOR = "synthetic.executor.one"
SECURITY = "synthetic.securityiam.one"
# The audit actions of one candidate's decision chain (its evidence observations are counted, not listed).
CHAIN_ACTIONS = ("CANDIDATE_CREATED", "TRANSITION_APPLIED", "TRANSITION_REFUSED", "APPROVAL_RECORDED",
                 "REMEDIATION_DRY_RUN_RECORDED", "GOVERNED_REQUEST_REFUSED")

NOTES = (
    "Synthetic and sanitized: every identity, group, application, policy, approval, provider state, and audit "
    "event below belongs to the fictional company Null Meridian, generated by this repository. "
    "'nullmeridian.info' is that fictional company's own name; OGWA never resolves or contacts it.",
    "Generated, not hand-written: every object is a verbatim subtree of the API response named by its 'source', "
    "from a fresh in-memory demo seed with a deterministic synthetic clock and deterministic request ids. No session "
    "cookie, CSRF token, credential, or secret is recorded.",
    "Persisted vs not: the policy versions, decisions, approvals, refusals, and the governed dry-run record are audit "
    "events in the store's hash chain (each with its sequence, digest, and previous digest). A synthetic execution "
    "drill records nothing: its result exists only in the API response, and the audit head is unchanged by it "
    "('auditHead' before and after).",
    "Synthetic execution means the change was submitted to an in-memory synthetic provider fixture, discarded after "
    "the response. No external provider or persistent environment was modified.",
)


class _Client:
    """A minimal in-process WSGI client: JSON in, JSON out, the session kept privately."""

    def __init__(self, api) -> None:
        self._api, self._cookie, self._csrf = api, None, None

    def request(self, method: str, path: str, body: Any = None) -> tuple[int, dict[str, Any]]:
        path, _, query = path.partition("?")
        payload = b"" if body is None else json.dumps(body).encode()
        environ: dict[str, Any] = {"REQUEST_METHOD": method, "PATH_INFO": path, "QUERY_STRING": query,
                                   "SERVER_NAME": "127.0.0.1", "SERVER_PORT": "8765", "wsgi.url_scheme": "http",
                                   "wsgi.input": io.BytesIO(payload)}
        if method == "POST":
            environ["CONTENT_TYPE"], environ["CONTENT_LENGTH"] = "application/json", str(len(payload))
            if self._csrf:
                environ["HTTP_" + CSRF_HEADER.upper().replace("-", "_")] = self._csrf
        if self._cookie:
            environ["HTTP_COOKIE"] = f"{SESSION_COOKIE}={self._cookie}"
        captured: dict[str, Any] = {}

        def start_response(status, headers):
            captured["status"], captured["headers"] = int(status.split(" ", 1)[0]), headers

        body_bytes = b"".join(self._api(environ, start_response))
        if path == f"{V}/session" and captured["status"] == 201:
            cookie = next(v for k, v in captured["headers"] if k.lower() == "set-cookie")
            self._cookie = cookie.split(";", 1)[0].split("=", 1)[1]
        out = json.loads(body_bytes.decode("utf-8"))
        if path == f"{V}/session" and captured["status"] == 201:
            self._csrf = out["csrfToken"]
        return captured["status"], out

    def sign_in(self, subject: str) -> "_Client":
        status, _ = self.request("POST", f"{V}/session", {"subject": subject})
        if status != 201:
            raise RuntimeError(f"synthetic sign-in failed for {subject}: {status}")
        return self

    def ok(self, method: str, path: str, body: Any = None, expect: int = 200) -> dict[str, Any]:
        status, out = self.request(method, path, body)
        if status != expect:
            raise RuntimeError(f"{method} {path}: expected {expect}, got {status}: {json.dumps(out)[:400]}")
        return out


def _head(client: _Client) -> dict[str, Any]:
    item = client.ok("GET", f"{V}/audit-events?limit=1")["items"][0]
    return {"source": "GET /api/v1/audit-events?limit=1 -> items[0] (sequence, digest)",
            "sequence": item["sequence"], "digest": item["digest"]}


def _chain(client: _Client, candidate_id: str) -> dict[str, Any]:
    page = client.ok("GET", f"{V}/candidates/{candidate_id}/audit-events?limit=200")
    if page["page"].get("nextCursor"):
        raise RuntimeError(f"{candidate_id} has more than one page of audit events")
    items = sorted(page["items"], key=lambda e: e["sequence"])
    return {"source": f"GET /api/v1/candidates/{candidate_id}/audit-events, oldest first, the decision chain's "
                      f"actions ({', '.join(CHAIN_ACTIONS)}); every event is part of the store's one hash chain",
            "events": [e for e in items if e["action"] in CHAIN_ACTIONS],
            "otherEventCounts": {a: sum(1 for e in items if e["action"] == a)
                                 for a in sorted({e["action"] for e in items} - set(CHAIN_ACTIONS))}}


def _drill_body(fingerprint: str, approval_id: str, assignment_id: str, mode: str, scenario: str | None = None):
    body = {"operation": "OKTA_GROUP_UNASSIGN", "target": {"assignmentId": assignment_id}, "approvalId": approval_id,
            "expectedEvidenceFingerprint": fingerprint, "mode": mode}
    if scenario is not None:
        body["scenario"] = scenario
    return body


def build_audit_sample() -> dict[str, Any]:
    """Seed, serve, ask, and return the sample. Deterministic: the same build gives the same bytes."""
    clock = SeedClock(AS_OF + HOUR)
    store, summary = create_null_meridian_store(parse_database_url("sqlite:///:memory:"), clock=clock)
    try:
        with deterministic_ids(f"{SEED}:audit-sample"):
            return _sample(store, summary, clock)
    finally:
        store.close()


def _sample(store, summary, clock) -> dict[str, Any]:
    api = build_local_api(store, clock=clock)
    ids = {s.key: s.candidate_id for s in summary.scenarios}
    c10, c11 = ids["NM-C10"], ids["NM-C11"]
    security = _Client(api).sign_in(SECURITY)
    executor = _Client(api).sign_in(EXECUTOR)
    seeded_head = _head(security)
    policy = security.ok("GET", f"{V}/policy")

    # --- Scenario A: NM-C10, incomplete and conflicting evidence: safe non-action --------------
    a_detail = security.ok("GET", f"{V}/candidates/{c10}")
    a_approval_status, a_approval = security.request("POST", f"{V}/candidates/{c10}/approvals", {
        "stage": "OKTA_UNASSIGN", "decision": "APPROVE", "reason": "OGWA-DEMO-04 audit sample: a reviewer tries to "
        "approve NM-C10", "expectedEvidenceFingerprint": a_detail["evidenceFingerprint"]})
    a_approvals = security.ok("GET", f"{V}/candidates/{c10}/approvals")
    # NM-C10 has no approval of its own; another candidate's approval is not borrowed.
    c11_approval = security.ok("GET", f"{V}/candidates/{c11}/approvals")["items"][0]["id"]
    a_drill_status, a_drill = executor.request("POST", f"{V}/candidates/{c10}/remediation-drills", _drill_body(
        a_detail["evidenceFingerprint"], c11_approval, store.load_candidate(c10).assignment_ids[0], "DRY_RUN"))
    scenario_a = {
        "candidateKey": "NM-C10", "candidateId": c10,
        "evidenceAssessment": {"source": f"GET /api/v1/candidates/{c10} -> evidenceAssessment",
                               **a_detail["evidenceAssessment"]},
        "decisionExplanation": {"source": f"GET /api/v1/candidates/{c10} -> decisionExplanation",
                                **a_detail["decisionExplanation"]},
        "approvalAttempt": {"source": f"POST /api/v1/candidates/{c10}/approvals (as {SECURITY})",
                            "status": a_approval_status, "response": a_approval},
        "approvalsAfter": {"source": f"GET /api/v1/candidates/{c10}/approvals", **a_approvals},
        "drillAttemptWithAnotherCandidatesApproval": {
            "source": f"POST /api/v1/candidates/{c10}/remediation-drills (as {EXECUTOR}, citing NM-C11's approval)",
            "status": a_drill_status, "response": a_drill},
        "auditChain": _chain(security, c10),
    }

    # --- Scenario B: NM-C11, controlled synthetic remediation -----------------------------------
    b_detail = security.ok("GET", f"{V}/candidates/{c11}")
    b_evidence = security.ok("GET", f"{V}/candidates/{c11}/evidence")
    fingerprint, assignment = b_detail["evidenceFingerprint"], store.load_candidate(c11).assignment_ids[0]
    before_drills = _head(security)
    dry = executor.ok("POST", f"{V}/candidates/{c11}/remediation-drills",
                      _drill_body(fingerprint, c11_approval, assignment, "DRY_RUN"))
    run = executor.ok("POST", f"{V}/candidates/{c11}/remediation-drills",
                      _drill_body(fingerprint, c11_approval, assignment, "SYNTHETIC_EXECUTION", "TIMEOUT_NOT_APPLIED"))
    after_drills = _head(security)
    governed = executor.ok("POST", f"{V}/candidates/{c11}/remediation-dry-runs", {
        "operation": "OKTA_GROUP_UNASSIGN", "target": {"assignmentId": assignment}, "approvalId": c11_approval,
        "expectedEvidenceFingerprint": fingerprint}, expect=201)
    scenario_b = {
        "candidateKey": "NM-C11", "candidateId": c11,
        "evidenceSnapshot": {"source": f"GET /api/v1/candidates/{c11}/evidence", **b_evidence},
        "evidenceAssessment": {"source": f"GET /api/v1/candidates/{c11} -> evidenceAssessment",
                               **b_detail["evidenceAssessment"]},
        "decisionExplanation": {"source": f"GET /api/v1/candidates/{c11} -> decisionExplanation",
                                **b_detail["decisionExplanation"]},
        "decisions": {"source": f"GET /api/v1/candidates/{c11}/decisions",
                      **security.ok("GET", f"{V}/candidates/{c11}/decisions")},
        "approvals": {"source": f"GET /api/v1/candidates/{c11}/approvals",
                      **security.ok("GET", f"{V}/candidates/{c11}/approvals")},
        "auditHeadBeforeDrills": before_drills,
        "dryRun": {"source": f"POST /api/v1/candidates/{c11}/remediation-drills (DRY_RUN, as {EXECUTOR})", **dry},
        "syntheticExecution": {"source": f"POST /api/v1/candidates/{c11}/remediation-drills (SYNTHETIC_EXECUTION, "
                                         f"TIMEOUT_NOT_APPLIED, as {EXECUTOR})", **run},
        "auditHeadAfterDrills": after_drills,
        "governedDryRunRecorded": {"source": f"POST /api/v1/candidates/{c11}/remediation-dry-runs (as {EXECUTOR}): "
                                             "the governed, recorded dry run of the same approved change",
                                   **governed},
        "auditChain": _chain(security, c11),
    }
    return {
        "format": FORMAT,
        "title": "OGWA synthetic governance audit sample: NM-C10 (no safe action) and NM-C11 (controlled synthetic "
                 "remediation)",
        "generatedBy": "python -m app.demo.null_meridian.audit_sample --write docs/demo/samples/ogwa-audit-sample.json",
        "synthetic": True, "notes": list(NOTES),
        "dataset": {"key": DATASET_KEY, "seed": SEED, "asOf": AS_OF.isoformat(), "auditHeadAfterSeed": seeded_head},
        "policy": {"source": "GET /api/v1/policy -> inForce, versions", "inForce": policy["inForce"],
                   "versions": policy["versions"]},
        "scenarioA": scenario_a,
        "scenarioB": scenario_b,
        "auditHeadAtEnd": _head(security),
    }


def render(sample: dict[str, Any]) -> str:
    return json.dumps(sample, indent=2, sort_keys=True, ensure_ascii=False) + "\n"


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    group = parser.add_mutually_exclusive_group(required=True)
    group.add_argument("--write", type=Path, nargs="?", const=DEFAULT_PATH, help="write the sample to this path")
    group.add_argument("--check", type=Path, nargs="?", const=DEFAULT_PATH,
                       help="fail unless the file at this path is exactly what this build generates")
    args = parser.parse_args(argv)
    text = render(build_audit_sample())
    if args.write is not None:
        args.write.parent.mkdir(parents=True, exist_ok=True)
        args.write.write_text(text, encoding="utf-8")
        print(f"wrote {args.write} ({len(text.encode('utf-8'))} bytes)")
        return 0
    current = args.check.read_text(encoding="utf-8") if args.check.is_file() else None
    if current != text:
        print(f"{args.check} is not what this build generates; regenerate it with --write", file=sys.stderr)
        return 1
    print(f"{args.check} matches this build")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())


